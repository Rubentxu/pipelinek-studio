package dev.pipelinek.studio.cli

import org.junit.jupiter.api.Assertions.assertNotNull
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.DisplayName
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.attribute.PosixFilePermission

/**
 * Falsifiers for the SFW-H6.3
 * install-from-tarball workflow.
 *
 * The H6.3 install script is the
 * "distribution entrypoint" AAT: the
 * operator's first interaction with the
 * installed product is `install.sh`. The
 * tests pin:
 *  1. The `install.sh` script exists in
 *     the standalone dist (the script is
 *     generated by `:studio-cli:standaloneDist`).
 *  2. The script is executable.
 *  3. The script extracts the tar
 *     correctly (the standalone root
 *     dir is found).
 *  4. The script creates a `bin/studio`
 *     symlink at the requested prefix.
 *  5. The script runs `studio --version`
 *     and the result is non-empty
 *     (the "no-missing-classpath" AAT).
 */
@DisplayName("install.sh (SFW-H6.3 install-from-tarball)")
class InstallFromTarballH63Test {

    @Test
    fun `install sh exists in the standalone dist`(@TempDir tempDir: Path) {
        val tarball = findStandaloneTarballH63() ?: run {
            System.err.println("standalone tarball not found; the operator should run :studio-cli:standaloneDist first")
            return
        }
        val stage = extractTarballH63(tarball, tempDir)
        val installSh = stage.resolve("install.sh")
        assertTrue(
            Files.exists(installSh),
            "install.sh must be in the standalone dist; got $installSh",
        )
    }

    @Test
    fun `install sh is executable`(@TempDir tempDir: Path) {
        val tarball = findStandaloneTarballH63() ?: return
        val stage = extractTarballH63(tarball, tempDir)
        val installSh = stage.resolve("install.sh")
        if (!Files.exists(installSh)) return
        // POSIX executable bit (the build sets it; the test pins it).
        val perms = Files.getPosixFilePermissions(installSh)
        assertTrue(
            perms.contains(PosixFilePermission.OWNER_EXECUTE),
            "install.sh must be executable; got perms=$perms",
        )
    }

    @Test
    fun `install sh has the expected shebang`(@TempDir tempDir: Path) {
        val tarball = findStandaloneTarballH63() ?: return
        val stage = extractTarballH63(tarball, tempDir)
        val installSh = stage.resolve("install.sh")
        if (!Files.exists(installSh)) return
        val firstLine = Files.readAllLines(installSh).firstOrNull() ?: ""
        assertTrue(
            firstLine.startsWith("#!"),
            "install.sh must start with a shebang; got '$firstLine'",
        )
        assertTrue(
            firstLine.contains("bash"),
            "install.sh must use bash; got '$firstLine'",
        )
    }

    @Test
    fun `install sh creates bin-studio symlink at the requested prefix`(@TempDir tempDir: Path) {
        val tarball = findStandaloneTarballH63() ?: return
        val stage = extractTarballH63(tarball, tempDir)
        val installSh = stage.resolve("install.sh")
        if (!Files.exists(installSh)) return

        val prefix = tempDir.resolve("install-prefix")
        Files.createDirectories(prefix)
        val pb = ProcessBuilder(installSh.toString(), prefix.toString())
        pb.inheritIO()
        val p = pb.start()
        check(p.waitFor() == 0) { "install.sh failed with exit ${p.exitValue()}" }

        val symlink = prefix.resolve("bin/studio")
        assertTrue(
            Files.exists(symlink),
            "install.sh must create bin/studio at the prefix; got $symlink",
        )
        // The symlink must point to a file (the launcher) that exists.
        val target = Files.readSymbolicLink(symlink)
        assertTrue(
            Files.exists(target),
            "the bin/studio symlink must point to an existing launcher; got $target",
        )
        // The target must be the standalone launcher.
        val targetStr = target.toString()
        assertTrue(
            targetStr.endsWith("/bin/studio"),
            "the symlink target must be a bin/studio launcher; got $targetStr",
        )
    }

    @Test
    fun `install sh runs studio --version with non-empty output (no missing classpath)`(@TempDir tempDir: Path) {
        val tarball = findStandaloneTarballH63() ?: return
        val stage = extractTarballH63(tarball, tempDir)
        val installSh = stage.resolve("install.sh")
        if (!Files.exists(installSh)) return

        val prefix = tempDir.resolve("install-prefix")
        Files.createDirectories(prefix)
        // Run install.sh first so the symlink exists.
        ProcessBuilder(installSh.toString(), prefix.toString())
            .inheritIO()
            .start()
            .waitFor()

        // Now run `studio --version` via the symlink.
        val studioBin = prefix.resolve("bin/studio")
        val pb = ProcessBuilder(studioBin.toString(), "--version")
        pb.redirectErrorStream(true)
        val p = pb.start()
        val output = p.inputStream.bufferedReader(Charsets.UTF_8).use { it.readText() }.trim()
        val exit = p.waitFor()
        assertNotNull(output, "studio --version output must be non-null")
        assertTrue(
            output.isNotEmpty(),
            "studio --version output must be non-empty (the no-missing-classpath AAT); got '$output' (exit=$exit)",
        )
    }
}

// --------------------------------------------------------------------
// Test helpers
// --------------------------------------------------------------------

private fun findStandaloneTarballH63(): Path? {
    // The standalone dist lives at:
    //   studio-cli/build/standalone/studio-cli-standalone-X.Y.Z.tar
    val standaloneDir = Path.of("studio-cli", "build", "standalone")
    if (!Files.exists(standaloneDir)) return null
    Files.list(standaloneDir).use { stream ->
        return stream
            .filter { it.fileName.toString().endsWith(".tar") }
            .findFirst()
            .orElse(null)
    }
}

private fun extractTarballH63(tarball: Path, intoDir: Path): Path {
    Files.createDirectories(intoDir)
    val pb = ProcessBuilder("tar", "-xf", tarball.toString(), "-C", intoDir.toString())
    pb.inheritIO()
    val p = pb.start()
    check(p.waitFor() == 0) { "tar -xf $tarball failed with exit ${p.exitValue()}" }
    // The tarball contains a single root directory; find it.
    return Files.list(intoDir).use { stream ->
        stream.findFirst().orElseThrow {
            IllegalStateException("tarball $tarball did not contain a root directory")
        }
    }
}
