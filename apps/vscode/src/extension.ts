// PipelineK Studio VS Code extension — R5 EVO-C
//
// R5 EVO-C.T3 (2026-10-16): every request path now goes through
// `StudioConnection`, which validates the settings with the T2
// `validateStudioConfig` API (plus an explicit, session-scoped
// confirmation for plaintext HTTP) before it creates any client. The tree
// is reconciled against the authoritative collection reads on every
// (re)connect, the status indicator distinguishes idle/running/error/
// disconnected, and the run commands use the real journal, diagnostics and
// `POST /runs/{id}/cancel` routes.
//
// R5 EVO-C.T4 (2026-10-16): a `*.pipeline.kts` document is linked to an
// EXISTING experiment (persisted per document URI in `workspaceState`; see
// `fileAssociation.ts`) and the CodeLens shows that experiment and its
// current state. Seal + Run seals the current document source into the
// linked experiment and submits a scenario the studio actually serves from
// `GET /scenarios`. It never creates an experiment per click and never
// fabricates a scenario id.
//
// The generated `sdk.ts` is still used for the routes it covers; see
// `studioApi.ts` for the typed reads it does not (it is a generated
// artifact and is regenerated by `studio generate-sdk-ts`).

import * as vscode from "vscode";
import { resolveTimeoutMs, type StudioConfigInput } from "./config";
import { SseClient } from "./sseClient";
import { StudioApi, runIdempotencyKey } from "./studioApi";
import { StudioConnection, type ConnectionStatus } from "./connection";
import { StudioTreeProvider, type TreeElement } from "./treeView";
import { FileExperimentStore } from "./fileAssociation";

/**
 * R5 EVO-C.T3 status indicator: the four documented states. `running` means
 * the studio is connected AND a run is in flight; `idle` means connected with
 * nothing running; `error` means the last authoritative operation or the
 * configuration was rejected; `disconnected` means the event stream is down
 * (the client is retrying with backoff).
 */
export type IndicatorState = "idle" | "running" | "error" | "disconnected";

export function indicatorState(status: ConnectionStatus, counters: { running: number }): IndicatorState {
  if (status.kind === "error") return "error";
  if (status.kind === "disconnected") return "disconnected";
  if (counters.running > 0) return "running";
  return "idle";
}

export function statusBarText(status: ConnectionStatus, counters: { running: number }): string {
  switch (indicatorState(status, counters)) {
    case "error":
      return "$(error) Studio: error";
    case "disconnected":
      return "$(debug-disconnect) Studio: disconnected";
    case "running":
      return `$(sync~spin) Studio: running ${counters.running}`;
    case "idle":
      return status.kind === "connecting" ? "$(sync~spin) Studio: connecting" : "$(check) Studio: idle";
  }
}

function statusTooltip(
  status: ConnectionStatus,
  counters: { running: number; failed: number },
  lastRunId: string | undefined,
  config: { baseUrl: string; profile: string } | null,
): string {
  const lines = [`PipelineK Studio: ${status.kind}`, status.detail];
  if (config) lines.push(`${config.baseUrl} (profile ${config.profile})`);
  lines.push(`${counters.running} running, ${counters.failed} failed`);
  lines.push(lastRunId ? `Most recent run: ${lastRunId}` : "No runs known yet");
  return lines.join("\n");
}

function statusSummary(
  status: ConnectionStatus,
  counters: { running: number; failed: number },
  config: { baseUrl: string; profile: string } | null,
  lastRunId: string | undefined,
): string {
  const parts = [`PipelineK Studio: ${status.kind}`, status.detail];
  if (config) parts.push(`baseUrl=${config.baseUrl} profile=${config.profile}`);
  parts.push(`running=${counters.running}, failed=${counters.failed}`);
  if (lastRunId) parts.push(`lastRun=${lastRunId}`);
  return parts.join(" · ");
}

function readStudioSettings(): StudioConfigInput {
  const cfg = vscode.workspace.getConfiguration("pipelinekStudio");
  return {
    baseUrl: cfg.get<string>("baseUrl"),
    profile: cfg.get<string>("profile"),
    allowInsecureHttp: cfg.get<boolean>("allowInsecureHttp"),
  };
}

/**
 * Plaintext HTTP confirmation. Enabling `allowInsecureHttp` is not consent:
 * the operator must approve this exact URL, and the approval lives only in
 * this extension session (StudioConnection owns the set). TLS certificate
 * verification is never disabled anywhere in this extension.
 */
async function confirmInsecureHttp(baseUrl: string): Promise<boolean> {
  const choice = await vscode.window.showWarningMessage(
    `PipelineK Studio: connect to ${baseUrl} over plaintext HTTP?`,
    {
      modal: true,
      detail:
        "The studio was started with --insecure-http. Traffic to this exact URL is unencrypted. " +
        "This approval lasts for this VS Code session only; it is not persisted and does not apply to other URLs.",
    },
    "Allow HTTP",
  );
  return choice === "Allow HTTP";
}

function messageOf(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

function runIdOf(item?: TreeElement): string | undefined {
  return item && item.kind === "run" ? item.runId : undefined;
}

/**
 * The document a command addresses: an explicit URI (CodeLens argument),
 * a `Uri`, or the active editor. Undefined means the command cannot act.
 */
function documentUriOf(arg?: unknown): vscode.Uri | undefined {
  if (typeof arg === "string" && arg !== "") return vscode.Uri.parse(arg);
  if (arg instanceof vscode.Uri) return arg;
  return vscode.window.activeTextEditor?.document.uri;
}

function fileNameOf(uri: vscode.Uri): string {
  const segment = uri.path.split("/").filter((part) => part !== "");
  return segment[segment.length - 1] ?? uri.toString();
}

function isPipelineSource(uri: vscode.Uri): boolean {
  return uri.path.endsWith(".pipeline.kts");
}

type ExperimentPick = vscode.QuickPickItem & { experimentId: string };
type ScenarioPick = vscode.QuickPickItem & { scenarioId: string };

/**
 * CodeLens for `*.pipeline.kts` (S4: CodeLens/decorations without executing
 * code from the editor). It reports exactly what is known: the linked
 * experiment's name and the latest run state the tree has reconciled, or an
 * explicit "no linked experiment" affordance. The lens is refreshed on
 * source saves (the link can change elsewhere in the session) and whenever
 * the authoritative tree changes.
 */
class FileExperimentCodeLenses implements vscode.CodeLensProvider {
  private readonly onChanged = new vscode.EventEmitter<void>();
  readonly onDidChangeCodeLenses: vscode.Event<void> = this.onChanged.event;

  constructor(
    private readonly associations: FileExperimentStore,
    private readonly lookups: {
      nameOf(experimentId: string): string | undefined;
      stateOf(experimentId: string): string;
      latestRunOf(experimentId: string): TreeElement | undefined;
    },
  ) {}

  refresh(): void {
    this.onChanged.fire(undefined);
  }

  dispose(): void {
    this.onChanged.dispose();
  }

  provideCodeLenses(document: vscode.TextDocument): vscode.CodeLens[] {
    // CodeLens requires a Range; the lens is anchored at the first character
    // and the command reads the whole document. No code is executed in the
    // editor: the source goes to the studio as a sealed snapshot.
    const range = new vscode.Range(new vscode.Position(0, 0), new vscode.Position(0, 0));
    const uri = document.uri.toString();
    const lenses = [
      new vscode.CodeLens(range, {
        title: "Studio: Seal + Run",
        command: "pipelinek-studio.sealAndRun",
        arguments: [uri],
      }),
    ];
    const experimentId = this.associations.get(uri);
    if (!experimentId) {
      lenses.push(
        new vscode.CodeLens(range, {
          title: "Studio: No linked experiment",
          command: "pipelinek-studio.linkExperiment",
          arguments: [uri],
        }),
      );
      return lenses;
    }
    // A stable id is not a name: fall back to the id rather than inventing a
    // label, and report "no runs" instead of implying a successful run.
    const name = this.lookups.nameOf(experimentId) ?? experimentId;
    const state = this.lookups.stateOf(experimentId);
    const latestRun = this.lookups.latestRunOf(experimentId);
    lenses.push(
      new vscode.CodeLens(range, {
        title: `Studio: ${name} - ${state}`,
        command: latestRun ? "pipelinek-studio.openRun" : "pipelinek-studio.status",
        arguments: latestRun ? [latestRun] : [],
      }),
    );
    lenses.push(
      new vscode.CodeLens(range, {
        title: "Studio: Change linked experiment",
        command: "pipelinek-studio.linkExperiment",
        arguments: [uri],
      }),
    );
    return lenses;
  }
}

interface ActiveExtension {
  connection: StudioConnection;
  disposables: { dispose(): unknown }[];
}

let active: ActiveExtension | null = null;

export function activate(context: vscode.ExtensionContext): void {
  const log = vscode.window.createOutputChannel("PipelineK Studio");
  const timeoutMs = resolveTimeoutMs();
  const treeProvider = new StudioTreeProvider();
  const treeView = vscode.window.createTreeView("pipelinek-studio.tree", {
    treeDataProvider: treeProvider,
  });
  const statusBar = vscode.window.createStatusBarItem(vscode.StatusBarAlignment.Left, 100);
  statusBar.command = "pipelinek-studio.status";
  statusBar.show();

  let status: ConnectionStatus = { kind: "connecting", detail: "starting" };
  let lastRunId: string | undefined;
  /** Documents whose Seal + Run invocation is still in flight (one per document). */
  const sealsInFlight = new Set<string>();

  // T4: the association lives in `workspaceState`, so it survives a window
  // reload and a new activation; the lens reads it synchronously.
  const associations = new FileExperimentStore(context.workspaceState);
  const codeLenses = new FileExperimentCodeLenses(associations, {
    nameOf: (experimentId) => treeProvider.model.experiments.get(experimentId)?.name,
    stateOf: (experimentId) => {
      const [latest] = treeProvider.model.runsFor(experimentId);
      return latest ? latest.status : "no runs";
    },
    latestRunOf: (experimentId) => {
      const [latest] = treeProvider.model.runsFor(experimentId);
      if (!latest) return undefined;
      return {
        kind: "run",
        experimentId,
        runId: latest.runId,
        status: latest.status,
        startedAt: latest.startedAt,
      };
    },
  });

  const render = (): void => {
    const counters = treeProvider.model.counters();
    lastRunId = treeProvider.model.mostRecentRun()?.runId;
    statusBar.text = statusBarText(status, counters);
    statusBar.tooltip = statusTooltip(status, counters, lastRunId, connection.activeConfig);
  };

  const connection = new StudioConnection({
    readSettings: readStudioSettings,
    confirmInsecureHttp,
    createApi: (config) => new StudioApi(config, { timeoutMs }),
    createSse: (config) =>
      new SseClient({
        baseUrl: config.baseUrl,
        headers: config.headers,
        connectTimeoutMs: timeoutMs,
      }),
    onStatus: (next) => {
      status = next;
      render();
    },
    onEvent: (event) => {
      treeProvider.apply(event);
      log.appendLine(`tree event: ${event.kind} seq=${event.seq}`);
    },
    syncTree: (load) => treeProvider.reconcileWith(load),
    log: (line) => log.appendLine(line),
  });

  // An authoritative tree update changes what the lens can truthfully
  // report, so the same signal refreshes both.
  const onTreeChanged = treeProvider.onDidChangeTreeData(() => {
    render();
    codeLenses.refresh();
  });

  /** Open the run's real journal as JSONL, walking every page. */
  const openJournal = async (runId: string): Promise<void> => {
    const api = await connection.ensureApi();
    const events = await api.journal(runId);
    const jsonl = events.map((event) => JSON.stringify(event)).join("\n");
    const doc = await vscode.workspace.openTextDocument({ content: jsonl, language: "json" });
    await vscode.window.showTextDocument(doc, { preview: false });
  };

  const openRunById = async (runId: string): Promise<void> => {
    try {
      await openJournal(runId);
    } catch (e) {
      vscode.window.showErrorMessage(`Open run failed: ${messageOf(e)}`);
    }
  };

  const disposables: { dispose(): unknown }[] = [
    log,
    statusBar,
    treeView,
    connection,
    vscode.workspace.onDidChangeConfiguration((e) => {
      if (!e.affectsConfiguration("pipelinekStudio")) return;
      // Dispose the old client and revalidate before any new request can
      // use the changed URL/profile/HTTP setting.
      void connection.reload();
    }),
    onTreeChanged,
    codeLenses,
    // The link can change while the document is open; a save is the moment
    // the operator expects the lens to tell the truth again.
    vscode.workspace.onDidSaveTextDocument((document) => {
      if (isPipelineSource(document.uri)) codeLenses.refresh();
    }),
    vscode.commands.registerCommand("pipelinek-studio.status", async () => {
      // The indicator is also the last-run entry point: clicking it opens
      // the most recent run's detail when one is known.
      if (lastRunId !== undefined) {
        await openRunById(lastRunId);
        return;
      }
      vscode.window.showInformationMessage(
        statusSummary(status, treeProvider.model.counters(), connection.activeConfig, lastRunId),
      );
    }),
    vscode.commands.registerCommand("pipelinek-studio.health", async () => {
      try {
        const api = await connection.ensureApi();
        const body = await api.health();
        vscode.window.showInformationMessage(`PipelineK Studio /health -> ${body}`);
      } catch (e) {
        vscode.window.showErrorMessage(`Studio unreachable: ${messageOf(e)}`);
      }
    }),
    vscode.commands.registerCommand("pipelinek-studio.createExperiment", async () => {
      const name = await vscode.window.showInputBox({
        prompt: "Experiment name",
        placeHolder: "e.g. nightly-cache-bench",
      });
      if (!name) return;
      try {
        const api = await connection.ensureApi();
        const created = await api.createExperiment(name);
        vscode.window.showInformationMessage(`Created experiment ${created.experimentId}: ${created.name}`);
        await connection.refreshTree().catch(() => undefined);
      } catch (e) {
        vscode.window.showErrorMessage(`Create experiment failed: ${messageOf(e)}`);
      }
    }),
    vscode.commands.registerCommand("pipelinek-studio.listSteps", async () => {
      try {
        const api = await connection.ensureApi();
        const steps = await api.listSteps();
        if (steps.length === 0) {
          vscode.window.showInformationMessage("No steps admitted by the Studio.");
          return;
        }
        const picked = await vscode.window.showQuickPick(
          steps.map((step) => ({ label: step.id, description: step.name ?? "" })),
          { placeHolder: `${steps.length} steps admitted by the Studio` },
        );
        if (picked) {
          vscode.window.showInformationMessage(`Selected step: ${picked.label}`);
        }
      } catch (e) {
        vscode.window.showErrorMessage(`List steps failed: ${messageOf(e)}`);
      }
    }),
    vscode.commands.registerCommand("pipelinek-studio.openOpenApi", async () => {
      try {
        const api = await connection.ensureApi();
        const text = await api.openapiDocument();
        const doc = await vscode.workspace.openTextDocument({ content: text, language: "json" });
        await vscode.window.showTextDocument(doc, { preview: true });
      } catch (e) {
        vscode.window.showErrorMessage(`OpenAPI fetch failed: ${messageOf(e)}`);
      }
    }),
    vscode.commands.registerCommand("pipelinek-studio.tree.refresh", async () => {
      try {
        await connection.refreshTree();
        vscode.window.showInformationMessage("PipelineK Studio tree refreshed from the studio.");
      } catch (e) {
        vscode.window.showErrorMessage(`Studio tree refresh failed: ${messageOf(e)}`);
      }
    }),
    // R5 EVO-C.3: open a run's event journal (JSONL, paginated).
    vscode.commands.registerCommand("pipelinek-studio.openRun", async (item?: TreeElement) => {
      const runId = runIdOf(item);
      if (!runId) {
        vscode.window.showErrorMessage("Select a run in the Studio tree to open it.");
        return;
      }
      await openRunById(runId);
    }),
    // R5 EVO-C.3: diagnostics + output stay a separate read (S3: "acceder
    // a diagnósticos"); the journal is not the diagnostics plane.
    vscode.commands.registerCommand("pipelinek-studio.runDiagnostics", async (item?: TreeElement) => {
      const runId = runIdOf(item);
      if (!runId) {
        vscode.window.showErrorMessage("Select a run in the Studio tree to inspect.");
        return;
      }
      try {
        const api = await connection.ensureApi();
        const diagnostics = await api.diagnostics(runId);
        const output = await api.output(runId);
        const doc = await vscode.workspace.openTextDocument({
          content: JSON.stringify({ runId, diagnostics, output }, null, 2),
          language: "json",
        });
        await vscode.window.showTextDocument(doc, { preview: false });
      } catch (e) {
        vscode.window.showErrorMessage(`Open run diagnostics failed: ${messageOf(e)}`);
      }
    }),
    // R5 EVO-C.4: cancel a run. The real route is POST /runs/{id}/cancel
    // (EVO-C.5 reconciliation: `/experiments/{id}/cancel` is not a second
    // semantic). The result is reported as the studio answered it: an
    // acknowledgement is not a terminal state.
    vscode.commands.registerCommand("pipelinek-studio.cancelRun", async (item?: TreeElement) => {
      const runId = runIdOf(item);
      if (!runId) {
        vscode.window.showErrorMessage("Select a run in the Studio tree to cancel.");
        return;
      }
      try {
        const api = await connection.ensureApi();
        const outcome = await vscode.window.withProgress(
          {
            location: vscode.ProgressLocation.Notification,
            title: `PipelineK Studio: cancelling run ${runId}`,
            cancellable: false,
          },
          async (progress) => {
            progress.report({ message: "POST /runs/{id}/cancel" });
            return api.cancelRun(runId);
          },
        );
        if (outcome.kind === "acknowledged") {
          vscode.window.showInformationMessage(`Cancel ${runId}: acknowledged by the studio`);
          await connection.refreshTree().catch(() => undefined);
        } else {
          vscode.window.showErrorMessage(`Cancel ${runId} failed: ${outcome.detail}`);
        }
      } catch (e) {
        vscode.window.showErrorMessage(`Cancel run failed: ${messageOf(e)}`);
      }
    }),
    vscode.languages.registerCodeLensProvider([{ pattern: "**/*.pipeline.kts" }], codeLenses),
    // T4: link (or change) the document's experiment. An experiment is only
    // ever chosen from the studio's authoritative collection: the extension
    // never creates one as a side effect of linking or running.
    vscode.commands.registerCommand("pipelinek-studio.linkExperiment", async (uriArg?: unknown) => {
      const uri = documentUriOf(uriArg);
      if (!uri) {
        vscode.window.showErrorMessage("Open a *.pipeline.kts document to link it to a Studio experiment.");
        return;
      }
      const uriKey = uri.toString();
      let experiments: { id: string; name: string }[];
      try {
        const api = await connection.ensureApi();
        experiments = (await api.experiments()).items;
      } catch (e) {
        vscode.window.showErrorMessage(`Link experiment failed: ${messageOf(e)}`);
        return;
      }
      if (experiments.length === 0) {
        vscode.window.showInformationMessage(
          "The studio has no experiments yet. Create one with 'Studio: Create Experiment'; linking never creates an experiment.",
        );
        return;
      }
      const current = associations.get(uriKey);
      const picked = await vscode.window.showQuickPick<ExperimentPick>(
        experiments.map((experiment) => ({
          label: experiment.name,
          description: experiment.id,
          experimentId: experiment.id,
        })),
        {
          placeHolder: current
            ? `Linked experiment: ${current}. Select another existing experiment to change it.`
            : "Select an existing experiment for this file",
        },
      );
      // Cancelled pick: no persistent write, no request.
      if (!picked) return;
      await associations.set(uriKey, picked.experimentId);
      codeLenses.refresh();
      const name = experiments.find((experiment) => experiment.id === picked.experimentId)?.name ?? picked.experimentId;
      vscode.window.showInformationMessage(
        `Linked ${fileNameOf(uri)} to experiment ${name} (${picked.experimentId}).`,
      );
    }),
    // R5 EVO-C.T4: Seal + Run seals the current document source into the
    // linked experiment and submits a scenario the studio really serves
    // (`GET /scenarios`). It creates no experiment, invents no scenario and
    // runs no code locally; the only execution is the studio's own run.
    //
    // One invocation per document at a time: a double-click (or a lens click
    // racing the command) must not open two pickers, seal twice and submit
    // two runs. The guard is per document and released in `finally`, so a
    // deliberate later invocation still runs normally.
    vscode.commands.registerCommand("pipelinek-studio.sealAndRun", async (uriArg?: unknown) => {
      const uri = documentUriOf(uriArg);
      if (!uri) {
        vscode.window.showErrorMessage("Open a *.pipeline.kts document to seal and run it.");
        return;
      }
      const uriKey = uri.toString();
      if (sealsInFlight.has(uriKey)) {
        log.appendLine(`Seal+Run for ${uriKey} is already in progress; ignoring the duplicate invocation`);
        return;
      }
      sealsInFlight.add(uriKey);
      try {
        const experimentId = associations.get(uriKey);
        if (!experimentId) {
          vscode.window.showErrorMessage(
            "This file is not linked to a Studio experiment. Use 'Studio: Link experiment' first; Seal + Run never creates an experiment for you.",
          );
          return;
        }
        const api = await connection.ensureApi();
        // The association is a hint until the studio confirms it: an id the
        // studio no longer has must not become a seal or a submit target.
        const experiments = await api.experiments();
        const experiment = experiments.items.find((candidate) => candidate.id === experimentId);
        if (!experiment) {
          vscode.window.showErrorMessage(
            `Linked experiment ${experimentId} does not exist in the studio. Link this file to an existing experiment first.`,
          );
          return;
        }
        const scenarios = await api.scenarios();
        if (scenarios.items.length === 0) {
          vscode.window.showErrorMessage(
            "The studio has no registered scenarios (GET /scenarios). Register a scenario before running; Seal + Run never invents a scenario id.",
          );
          return;
        }
        const picked = await vscode.window.showQuickPick<ScenarioPick>(
          scenarios.items.map((scenario) => ({
            label: scenario.scenarioId,
            description: `v${scenario.version} - ${scenario.environmentProfile}`,
            scenarioId: scenario.scenarioId,
          })),
          { placeHolder: `Scenario for experiment ${experiment.name}` },
        );
        // Cancelled scenario selection: no seal request, no submit.
        if (!picked) return;

        // The open document, so unsaved edits are what gets sealed.
        const document = await vscode.workspace.openTextDocument(uri);
        const source = document.getText();
        const snapshot = await api.sealSnapshot(experimentId, source, "vscode");
        const run = await api.startRun(
          experimentId,
          snapshot.snapshotId,
          picked.scenarioId,
          runIdempotencyKey(snapshot.snapshotId, picked.scenarioId),
        );
        log.appendLine(
          `Seal+Run: exp=${experimentId} snap=${snapshot.snapshotId} scenario=${picked.scenarioId} run=${run.runId}`,
        );
        await connection.refreshTree().catch(() => undefined);
        // The run is only ever reachable through its true id: no placeholder.
        const choice = await vscode.window.showInformationMessage(
          `Seal+Run: run id ${run.runId} (${run.state})`,
          "Open Run",
        );
        if (choice === "Open Run") await openRunById(run.runId);
      } catch (e) {
        vscode.window.showErrorMessage(`Seal+Run failed: ${messageOf(e)}`);
      } finally {
        sealsInFlight.delete(uriKey);
      }
    }),
  ];

  context.subscriptions.push(...(disposables as unknown as vscode.Disposable[]));
  active = { connection, disposables };
  render();
  log.appendLine("PipelineK Studio extension activated");
  connection.start();
}

export function deactivate(): void {
  const current = active;
  active = null;
  if (!current) return;
  current.connection.dispose();
  for (const disposable of current.disposables) {
    try {
      disposable.dispose();
    } catch {
      // A disposable that failed to release must not block deactivation.
    }
  }
}
