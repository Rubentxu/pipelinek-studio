package dev.pipelinek.studio.http

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

/**
 * Wire-level JSON shapes for the HTTP API. Per docs/02-specifications/HTTP_AND_STREAMING_API.md
 * these are versioned via the OpenAPI schema; breaking changes require a v2 route.
 */

@Serializable
data class ErrorResponse(
    val code: String,
    val message: String,
    val phase: String? = null,
    val actions: List<String> = emptyList(),
    /**
     * B2.2 (2026-10-10): opaque correlation handle the
     * server-side catch-all puts on the wire so the
     * operator can ask the studio log for the matching
     * exception without exposing the original cause.
     * Nullable so existing typed error sites
     * (BAD_REQUEST, RUNTIME_UNAVAILABLE, etc.) don't have
     * to invent an id — the handle is for the catch-all.
     */
    @SerialName("error_id") val errorId: String? = null,
)

@Serializable
data class RunEventDto(
    val sequence: Long,
    val kind: String,
    val occurredAt: String,
    val payload: Map<String, String>,
)

@Serializable
data class RunEventsResponse(
    val runId: String,
    val events: List<RunEventDto>,
    val nextSequence: Long? = null,
)

/**
 * Output Plane response shape. The OutputChunk domain type carries
 * raw bytes (ByteArray) which is not @Serializable. The HTTP layer
 * always encodes bytes as base64 so the wire contract is unambiguous
 * (charset-free, byte-faithful). The SPA decodes base64 + applies
 * UTF-8 locally, which preserves non-UTF-8 bytes for diagnostic
 * surfaces without losing information on the wire.
 */
@Serializable
data class OutputChunkDto(
    val streamId: String,
    val bytesBase64: String,
    val cursor: String,
    val eof: Boolean,
)

@Serializable
data class OutputReadResponse(
    val runId: String,
    val chunks: List<OutputChunkDto>,
    val nextCursor: String,
)

/**
 * S5 server-side restart reconciliation report. The report is
 * generated by [dev.pipelinek.studio.infra.sdk.RunReconciler] which
 * walks the per-run control-root dir and surfaces each in-flight
 * run as RECOVERY_REQUIRED (or LOST when no events were ever
 * written) so the operator can see what state the subprocess is
 * in after a studio restart. The report is read-only — the
 * operator decides what to do next (cancel, restart, etc.).
 */
@Serializable
data class RecoveryEntryDto(
    val runId: String,
    val state: String,
    val lastEventKind: String? = null,
    val lastEventAt: String? = null,
    val reason: String,
)

